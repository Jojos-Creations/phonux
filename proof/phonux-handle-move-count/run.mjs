// node run.mjs <bundle.js> [chromium|webkit|firefox]
import { createServer } from 'node:http';
import { readFileSync } from 'node:fs';
const pw = await import(process.env.PLAYWRIGHT_MODULE ?? '/opt/node22/lib/node_modules/playwright/index.mjs');
const [bundle, engine = 'chromium'] = process.argv.slice(2);
const srv = createServer((q, s) => {
  const js = q.url.startsWith('/out.js');
  s.setHeader('content-type', js ? 'text/javascript' : 'text/html');
  s.end(js ? readFileSync(bundle) : readFileSync(new URL('./index.html', import.meta.url)));
}).listen(0);
const browser = await pw[engine].launch();
const page = await (await browser.newContext({ viewport: { width: 2000, height: 900 } })).newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text().slice(0, 200)); });
let failed = 0;
const check = (name, ok, detail = '') => { if (!ok) failed++; console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${detail ? ` :: ${detail}` : ''}`); };
await page.goto(`http://localhost:${srv.address().port}/`);
await page.waitForSelector('[data-body="four"]');
await page.waitForTimeout(800);
const order = () => page.evaluate(() => [...document.querySelectorAll('[data-body]')].map((n) => n.dataset.body).filter((b) => b !== 'root'));
check('start order', (await order()).join() === 'one,two,three,four', (await order()).join());
const grab = page.locator('[data-body="one"]').locator('xpath=ancestor::*[@data-row-slot][1]').locator('[data-panel-grab-bar]');
const box = await grab.boundingBox();
const x = box.x + box.width / 2, y = box.y + box.height / 2;
await page.mouse.move(x, y);
await page.mouse.down();
for (let i = 1; i <= 20; i += 1) { await page.mouse.move(x + i * 45, y); await page.waitForTimeout(16); }
await page.waitForTimeout(150);
await page.mouse.up();
await page.waitForTimeout(800);
check('a real drag across two neighbours reorders in one release', (await order()).join() === 'two,three,one,four', (await order()).join());
const moveBy = (by) => page.evaluate((n) => { const r = window.__ws.panels.get('four').move(n, 'person'); return `${r.ok}:${r.changed}`; }, by);
const first = await moveBy(-3);
await page.waitForTimeout(600);
const second = await moveBy(-9);
await page.waitForTimeout(600);
check('move(-3) crosses three slots as one accepted result', first === 'true:true', first);
check('move(-9) runs out at the row start (it crosses History, then stops)', second === 'true:true', second);
const third = await moveBy(-9);
check('move(-9) at the row start changes nothing', third === 'true:false', third);
check('no console errors', errors.length === 0, errors.join(' | '));
await browser.close();
srv.close();
process.exit(failed ? 1 : 0);
