import { createRoot } from 'react-dom/client';
import { createWorkspace, definePanel } from 'LIB/index.js';
import { AutoRoot } from 'LIB/autoMount.js';
const q = new URLSearchParams(location.search);
const slots = (q.get('slots') ?? '1,1,1,1,1,1,1').split(',').map(Number);
const view = (name: string) => () => <div data-body={name} style={{ height: '100%', background: '#335', color: '#fff', font: '20px sans-serif' }}>{name}</div>;
const ts = slots.map((s, k) => definePanel({ id: `p${k}`, settings: { title: `p${k}`, slots: s, maxSlots: 64 }, view: view(`p${k}`) }));
const ws = createWorkspace({ mount: false, root: definePanel({ id: 'root', settings: { title: 'History' }, view: view('History') }), templates: ts, tuning: { rowGap: 16, rowGesture: (q.get('gesture') ?? 'step') as any, shrinkOutOfView: (q.get('shrink') ?? 'off') as any } });
for (let k = 0; k < ts.length; k++) ws.addPanel(`p${k}`);
const el = document.createElement('div');
el.style.cssText = 'position:fixed;inset:0';
document.body.appendChild(el);
createRoot(el).render(<AutoRoot workspace={ws} />);
