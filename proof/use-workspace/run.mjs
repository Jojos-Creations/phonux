// node run.mjs <bundle.js> [chromium|webkit|firefox]
import { createServer } from 'node:http';
import { readFileSync } from 'node:fs';
const pw = await import(process.env.PLAYWRIGHT_MODULE ?? '/opt/node22/lib/node_modules/playwright/index.mjs');
const [bundle, engine = 'chromium'] = process.argv.slice(2);
const srv = createServer((q, s) => {
  const js = q.url.startsWith('/out.js');
  s.setHeader('content-type', js ? 'text/javascript' : 'text/html');
  s.end(js ? readFileSync(bundle) : readFileSync(new URL('./index.html', import.meta.url)));
}).listen(0);
const browser = await pw[engine].launch();
const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(`${m.type()}: ${m.text().slice(0, 200)}`); });
let failed = 0;
const check = (name, ok, detail = '') => { if (!ok) failed++; console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${detail ? ` :: ${detail}` : ''}`); };
await page.goto(`http://localhost:${srv.address().port}/`);
await page.waitForFunction(() => window.__ws?.status === 'ready');
const ids = await page.evaluate(() => [1, 2, 3].map(() => window.__ws.addPanel('web').id));
await page.waitForTimeout(500);
check('three panels made with keys web~2 and web~3 among them', ids.includes('web~2') && ids.includes('web~3'), ids.join(', '));
const shape = await page.evaluate(() => Object.keys(window.__viewWorkspace ?? {}).concat(Object.keys(window.__viewWorkspace?.panels ?? {}).sort()));
check('a view got the workspace: panels with addPanel, no dispose', shape.includes('panels') && shape.includes('addPanel') && !shape.includes('dispose'), shape.join(','));
const status = (id) => page.evaluate((k) => window.__ws.panels.get(k)?.getState().status, id);
await page.click('[data-hide]');
await page.waitForTimeout(400);
check('hide(web~3) from the view parked it', (await status('web~3')) === 'parked', await status('web~3'));
await page.click('[data-show]');
await page.waitForTimeout(500);
check('show(web~3) from the view made it live again', (await status('web~3')) === 'live', await status('web~3'));
await page.click('[data-close]');
await page.waitForTimeout(500);
check('close(web~2) from the view closed it', (await status('web~2')) === 'closed', await status('web~2'));
await page.click('[data-add]');
await page.waitForTimeout(500);
const added = await page.evaluate((known) => window.__ws.panels.list().map((h) => h.id).filter((id) => id !== 'root' && !known.includes(id)), ids);
check('addPanel from the view made one more panel, drawn on the page', added.length === 1 && (await status(added[0])) === 'live' && (await page.$(`[data-box="${added[0]}"]`)) !== null, added.join(', '));
check('no console errors or warnings', errors.length === 0, errors.join(' | '));
await browser.close();
srv.close();
process.exit(failed ? 1 : 0);
